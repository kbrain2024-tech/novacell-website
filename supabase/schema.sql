create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id,email,full_name)
  values (new.id,lower(coalesce(new.email,'')),coalesce(new.raw_user_meta_data->>'full_name',''))
  on conflict (id) do update set email=excluded.email,full_name=excluded.full_name,updated_at=now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert or update of email,raw_user_meta_data on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.entitlements enable row level security;
alter table public.admin_users enable row level security;

grant usage on schema public to anon, authenticated;
grant select on public.products to anon, authenticated;
grant select on public.profiles, public.entitlements, public.admin_users to authenticated;

drop policy if exists "members read own profile" on public.profiles;
create policy "members read own profile" on public.profiles for select using (auth.uid() = id);
drop policy if exists "public reads active products" on public.products;
create policy "public reads active products" on public.products for select using (active = true);
drop policy if exists "members read own entitlements" on public.entitlements;
create policy "members read own entitlements" on public.entitlements for select using (auth.uid() = user_id);
drop policy if exists "admins read own admin row" on public.admin_users;
create policy "admins read own admin row" on public.admin_users for select using (auth.uid() = user_id);

